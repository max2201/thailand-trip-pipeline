def hit(rx,t,neg=True):
    for m in rx.finditer(t):
        if neg:
            pre=t[max(0,m.start()-40):m.start()]; post=t[m.end():m.end()+30]
            if PRE.search(pre) or POST.search(post): continue
        return True
    return False
def count_notes(d):
    """Счётчики фишек (fc) и тревожных сигналов (rc) по сырым отзывам отеля."""
    rv=[x for x in d["rev"] if x["t"] and len(x["t"].strip())>3]
    n=len(rv); fc={}; rc={}
    low=[x for x in rv if (x["r"] or 10)<=7]
    for k,l,rx in CF: fc[k]=sum(1 for x in rv if hit(rx,x["t"],k in NEGFEAT))
    for k,l,w,rx in CR_:
        src=low if k in ("notrec","photos","hardfind") else rv
        rc[k]=sum(1 for x in src if hit(rx,x["t"], k not in ("notrec",)))
    return n,fc,rc
